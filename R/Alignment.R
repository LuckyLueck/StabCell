#' Jaccard similarity
#'
#' This function calculates the Jaccard similarity between two boolean vectors.
#' It is sometimes also referred to as 'intersection over union'.
#'
#' \deqn{\frac{A \cap B}{A \cup B}}
#'
#' @param reference_selection,comparison_selection A pair of boolean vectors with the same length.
#'
#' @return A number between 0 and 1.
#'
#' @examplesIf FALSE
#' jaccard_similarity(c(T, T, T), c(T, T, F))
#'
#' @keywords internal
jaccard_similarity <- function(reference_selection, comparison_selection){
  intersection <- sum(reference_selection & comparison_selection)
  union <- sum(reference_selection | comparison_selection)
  return(intersection / union)
}

#' Find the closest cluster
#'
#' Given a reference cluster from a vector of reference allocations, this
#' function finds the closest cluster in terms of Jaccard similarity in a vector
#' of comparison allocations.
#'
#' @param reference_allocations,comparison_allocations Cluster label vectors with
#'        the same length.
#' @param reference_cluster_id Single cluster label from \code{reference_allocations}.
#'
#' @return The cluster label from \code{comparison_allocations} which minimizes the
#'         Jaccard Similarity between the clusters.
#'
#' @examplesIf FALSE
#' find_closest_cluster(c(1, 1, 2, 3), 1, c(2, 2, 2, 4))
#'
#' @keywords internal
find_closest_cluster <- function(
    reference_allocations,
    reference_cluster_id,
    comparison_allocations
){
  comparison_ids <- unique(comparison_allocations)
  jacc <- rep(0, length(comparison_ids))
  names(jacc) <- comparison_ids

  reference_selection <- reference_allocations == reference_cluster_id
  for(comparison_id in comparison_ids){
    comparison_selection <- comparison_allocations == comparison_id
    jacc[[as.character(comparison_id)]] <- jaccard_similarity(reference_selection, comparison_selection)
  }

  return(names(which.max(jacc)))
}



#' Align Clusters for Stable Marker Detection
#'
#' For each cluster in a reference clustering, find the closest cluster (in terms
#' of Jaccard similarity) in each subsample clustering. \code{NaN} values in each
#' subsample clustering are treated as "not sampled" and will be filtered out from
#' reference and subsample clusterings.
#' Parallelization can be achieved by setting a futures plan, e.g., \code{plan(multicore)}.
#'
#' @param reference_identities A vector of cluster labels. Usually the stable
#'        clustering generated by \emph{StabCell} is used.
#' @param subsampling_identities A matrix of subsampling cluster labels. Each row
#'        corresponds to a subsampling clustering. The number of columns must
#'        match the length of the reference identities.
#'
#' @return A \code{data.frame} with a columns for the subsample ID, the reference
#'         cluster ID, and the aligned subsample cluster ID.
#'
#' @importFrom tidyr crossing
#' @importFrom doRNG %dorng%
#' @importFrom foreach foreach getDoParRegistered registerDoSEQ
#'
#' @export
MarkerStabilityAlignment <- function(
    reference_identities,
    subsampling_identities
){
  subsampling_iterations <- nrow(subsampling_identities)

  unique_reference_identities <- sort(unique(reference_identities))

  # (parallel) alignment
  settings <- crossing(
    i=1:subsampling_iterations,
    j=1:length(unique_reference_identities)
  )

  if (!getDoParRegistered()) registerDoSEQ()
  df_alignment <- foreach(
    x=1:nrow(settings),
    .combine="rbind",
    .packages=c("Matrix"),
    .export=c(
      "find_closest_cluster",
      "jaccard_similarity"
    )
  ) %dorng% {
      i <- settings$i[x]
      j <- settings$j[x]

      # find observations used in respective subsampling run
      obs_idx <- !is.nan(subsampling_identities[i, ])
      subsampling_identities_i <- subsampling_identities[i, obs_idx]

      # align clusters
      reference_cluster_id <- unique_reference_identities[j]
      subsampling_cluster_id <- find_closest_cluster(
        reference_allocations=reference_identities[obs_idx],
        reference_cluster_id=reference_cluster_id,
        comparison_allocations=subsampling_identities_i
      )

      # compose result to return
      data.frame(
        subsample=i,
        reference_cluster_id=reference_cluster_id,
        subsampling_cluster_id=subsampling_cluster_id
      )
    }

  return(df_alignment)
}




#' Align Clusters for Cluster Stability
#'
#' For each cluster in each subsampling clustering, find the closest cluster (in
#' terms of Jaccard similarity) in the reference clustering. \code{NaN} values in
#' each subsample clustering are treated as "not sampled" and will be filtered
#' out from reference and subsample clusterings.
#' Parallelization can be achieved by setting a futures plan, e.g., \code{plan(multicore)}.
#'
#' @param reference_identities A vector of cluster labels. Usually an initial
#'        clustering of observations independent of \emph{StabCell} is used here.
#' @param subsampling_identities A matrix of subsampling cluster labels. Each row
#'        corresponds to a subsampling clustering. The number of columns must
#'        match the length of the reference identities.
#'
#' @return A \code{data.frame} with a columns for the subsample ID, the subsample
#'         cluster ID, and the aligned reference cluster ID.
#'
#' @importFrom doRNG %dorng%
#' @importFrom foreach foreach getDoParRegistered registerDoSEQ
#' @importFrom dplyr bind_rows
#'
#' @export
ClusterStabilityAlignment <- function(
    reference_identities,
    subsampling_identities
){
  subsampling_iterations <- nrow(subsampling_identities)

  # parallel alignment
  if (!getDoParRegistered()) registerDoSEQ()
  df_alignment <- foreach(
    i=1:subsampling_iterations,
    .combine="rbind",
    .packages=c("Matrix", "dplyr"),
    .export=c(
      "find_closest_cluster",
      "jaccard_similarity"
    )
  ) %dorng% {

    # find observations used in respective subsampling run
    obs_idx <- !is.nan(subsampling_identities[i, ])
    subsampling_identities_i <- subsampling_identities[i, obs_idx]

    unique_subsample_identities <- unique(subsampling_identities_i)

    subsample_list <- list()

    for(subsampling_cluster_id in unique_subsample_identities){


      # align clusters
      reference_cluster_id <- find_closest_cluster(
        reference_allocations=subsampling_identities_i,
        reference_cluster_id=subsampling_cluster_id,
        comparison_allocations=reference_identities[obs_idx]
      )

      # compose result to return
      subsample_list[[length(subsample_list) + 1]] <- data.frame(
        subsample=i,
        subsampling_cluster_id=subsampling_cluster_id,
        reference_cluster_id=reference_cluster_id
      )
    }

    bind_rows(subsample_list)

  }

  return(df_alignment)
}
